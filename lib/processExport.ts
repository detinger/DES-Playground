import { hasProcessCycle } from "./processEngine";
import python from "./exportRuntime/process.py?raw";
import r from "./exportRuntime/process.R?raw";
import type { DesModel } from "./model";
import type { RunConfig } from "./engine";
import { validateProcessModel } from "./processValidation";

export function generateProcessCode(
  model: DesModel,
  config: RunConfig,
  language: "python" | "r",
): string {
  if (config.stopMode !== "horizon" && hasProcessCycle(model))
    return "# Export unavailable: recurring cycles require Stop at horizon.\n";
  const errors = validateProcessModel(model);
  if (errors.hasErrors)
    return (
      "# Export unavailable: " +
      errors.issues
        .filter((i) => i.severity === "error")
        .map((i) => i.title)
        .join("; ") +
      "\n"
    );
  const modelText = JSON.stringify(JSON.stringify(model)),
    configText = JSON.stringify(JSON.stringify(config));
  return language === "python"
    ? "# DES Playground — SimPy process model\n# Install: pip install simpy matplotlib\nimport json\nMODEL = json.loads(" +
        modelText +
        ")\nCONFIG = json.loads(" +
        configText +
        ")\n\n" +
        python
    : '# DES Playground — R simmer process model\n# Packages installed automatically on first run.\n# R uses its own PRNG: compare distributions, not same-seed traces.\nMODEL <- jsonlite::fromJSON(' +
        modelText +
        ", simplifyVector=FALSE)\nCONFIG <- jsonlite::fromJSON(" +
        configText +
        ", simplifyVector=FALSE)\n\n" +
        r;
}

function nbCell(cell_type: "code" | "markdown", source: string) {
  const lines = source.split("\n").map((l, i, a) => (i < a.length - 1 ? l + "\n" : l));
  return cell_type === "code"
    ? { cell_type, metadata: {}, source: lines, outputs: [], execution_count: null }
    : { cell_type, metadata: {}, source: lines };
}

export function generateNotebook(model: DesModel, config: RunConfig): string {
  const code = generateProcessCode(model, config, "python");
  const slug = model.name.toLowerCase().replace(/\s+/g, "-");
  const cells = [
    nbCell(
      "markdown",
      `# ${model.name} — DES Simulation\n\nGenerated by [DES Playground](https://des-playground.app). Run each cell in order.`,
    ),
    nbCell("code", `!pip install -q simpy matplotlib numpy`),
    nbCell("code", code),
  ];
  return JSON.stringify(
    {
      nbformat: 4,
      nbformat_minor: 5,
      metadata: {
        kernelspec: { display_name: "Python 3", language: "python", name: "python3" },
        language_info: { name: "python", version: "3.9.0" },
        colab: { name: `${slug}.ipynb`, provenance: [] },
      },
      cells,
    },
    null,
    2,
  );
}
